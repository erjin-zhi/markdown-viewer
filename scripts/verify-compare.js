async (page) => {
  const results = [];
  const check = (ok, name) => { if (!ok) throw new Error(name); results.push(name); };
  await page.setViewportSize({ width: 1440, height: 1000 });
  const response = await page.goto("http://127.0.0.1:18765/diff");
  const original = await response.text();
  await page.locator("#markdown-lens-root").waitFor();
  const toggle = page.getByRole("switch", { name: "差异对比" });
  const editor = page.getByRole("textbox", { name: "Markdown 编辑器" });
  const left = page.locator(".diff-left .diff-scroll"), right = page.locator(".diff-right .diff-scroll");
  const settle = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  const top = loc => loc.evaluate(el => el.scrollTop);
  check((await page.locator(".view-tab").allTextContents()).join(",") === "预览,原文,编辑", "标签顺序");
  await toggle.check();
  check(await left.isVisible() && await right.isVisible(), "原文和编辑后双栏可见");
  check(await page.locator(".diff-summary").textContent() === "内容一致，暂无修改", "未编辑显示内容一致");
  check(await page.getByRole("button", {name:"下一处差异"}).isDisabled(), "无差异时禁用跳转");
  await page.getByRole("button", { name:"继续编辑", exact:true }).click();
  check(await editor.isVisible() && !await toggle.isChecked(), "继续编辑退出差异视图");
  const draft = original
    .replace("自动预览 Markdown 文档。", "自动预览、编辑和对比 Markdown 文档。")
    .replace("- 手动刷新预览\n", "")
    .replace("- 代码高亮\n", "- 代码高亮\n- 原文与编辑内容差异对比\n")
    .replace("第 55 条说明：支持 Markdown 文档。", "第 55 条说明：本地保存为 Markdown 文件。");
  await editor.fill(draft);
  await toggle.check();
  const textLines = panel => panel.locator(".diff-row:not(.placeholder) .diff-line-text").allTextContents();
  check((await textLines(left)).join("\n") + "\n" === original, "左栏逐行保持接口原文");
  check((await textLines(right)).join("\n") + "\n" === draft, "右栏逐行显示编辑后全文");
  check(await left.locator(".removed").count() === 1 && await right.locator(".added").count() === 1, "单独删除和新增标色");
  check(await left.locator(".modified").count() === 2 && await right.locator(".modified").count() === 2, "修改行两侧高亮");
  check((await right.locator(".diff-word-added").allTextContents()).join("").includes("编辑"), "中文行内修改高亮");
  check(await left.locator(".placeholder").count() === 1 && await right.locator(".placeholder").count() === 1, "插入删除空位对齐");
  check(await page.locator(".diff-summary").textContent() === "新增 3 行 · 删除 3 行 · 4 处差异", "准确显示增删行数和差异数量");
  check((await left.locator(".diff-line-number").allTextContents()).filter(Boolean).every((x, i) => +x === i+1), "原文行号连续");
  check((await right.locator(".diff-line-number").allTextContents()).filter(Boolean).every((x, i) => +x === i+1), "编辑后行号连续");
  await left.evaluate(el => { el.scrollTop = 700; });
  await settle();
  check(Math.abs(await top(left) - await top(right)) < 1 && await top(right) === 700, "原文滚动按对齐行同步");
  await right.evaluate(el => { el.scrollTop = 400; });
  await settle();
  check(Math.abs(await top(left) - await top(right)) < 1 && await top(left) === 400, "编辑后滚动反向同步");
  await page.getByRole("button", {name:"上一处差异"}).click();
  check(await page.locator(".change-position").textContent() === "4 / 4" && await top(left) > 1000, "上一处定位末尾差异");
  await page.getByRole("button", {name:"下一处差异"}).click();
  check(await page.locator(".change-position").textContent() === "1 / 4" && await top(left) < 200, "下一处循环回首处差异");
  check(await page.locator(".diff-row.current-change").count() === 2, "两侧标记当前差异");
  const divider = page.getByRole("separator", {name:"调整对比宽度"});
  await divider.press("ArrowRight");
  check(await divider.getAttribute("aria-valuenow") === "55", "键盘调整分栏");
  const bounds = await divider.boundingBox();
  await page.mouse.move(bounds.x + bounds.width/2, bounds.y + bounds.height/2);
  await page.mouse.down();
  await page.mouse.move(bounds.x + 90, bounds.y + bounds.height/2);
  await page.mouse.up();
  check(Number(await divider.getAttribute("aria-valuenow")) > 55, "拖动调整分栏");
  const [download] = await Promise.all([page.waitForEvent("download"), page.getByRole("button",{name:"保存文件",exact:true}).click()]);
  await download.saveAs("output/playwright/diff-edited.md");
  check(download.suggestedFilename() === "diff.md", "差异视图保存 Markdown 文件");
  await toggle.uncheck();
  check(await editor.inputValue() === draft && await editor.isVisible(), "关闭差异返回编辑并保留草稿");
  await toggle.check();
  await divider.press("Home");
  for(let i=0;i<4;i++) await divider.press("ArrowRight");
  await page.getByRole("button",{name:"返回顶部 ↑"}).click();
  await page.screenshot({path:"output/playwright/diff-desktop.png"});
  await page.locator(".theme-toggle").click();
  await page.screenshot({path:"output/playwright/diff-dark.png"});
  await page.locator(".theme-toggle").click();
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth), "窄屏没有页面横向溢出");
  check(await left.isVisible() && await right.isVisible(), "窄屏原文和编辑后上下排列");
  await right.evaluate(el => { el.scrollTop = 300; });
  await settle();
  check(Math.abs(await top(left) - await top(right)) < 1, "窄屏同步滚动");
  await page.getByRole("button",{name:"返回顶部 ↑"}).click();
  await page.screenshot({path:"output/playwright/diff-mobile.png"});
  await page.getByRole("button", { name:"继续编辑", exact:true }).click();
  await editor.fill(original + "<script>window.__diffXss=1</script><img src='/diff-track'>\n");
  await toggle.check();
  check(await right.locator("script,img").count() === 0 && !await page.evaluate(()=>window.__diffXss), "差异内容作为纯文本不会执行脚本或加载图片");
  check((await right.locator(".diff-line-text").allTextContents()).join("\n").includes("<script>"), "HTML 字面内容完整可见");
  await page.getByRole("button", { name:"继续编辑", exact:true }).click();
  await editor.fill("");
  await toggle.check();
  check(await right.locator(".diff-row:not(.placeholder)").count() === 0 && await left.locator(".removed").count() === original.split("\n").length-1, "清空编辑正确显示全部删除");
  await page.getByRole("button", { name:"继续编辑", exact:true }).click();
  await editor.fill(original.slice(0,-1));
  await toggle.check();
  check(await right.locator(".diff-eof").count() === 1, "末尾换行变化有明确标记");
  await page.getByRole("button", { name:"继续编辑", exact:true }).click();
  await editor.fill("a".repeat(500001));
  await toggle.check();
  check((await page.locator(".diff-summary").textContent()).includes("暂不生成 diff") && await page.getByRole("button",{name:"下一处差异"}).isDisabled(), "超限明确提示且不误报内容一致");
  await page.getByRole("button", { name:"继续编辑", exact:true }).click();
  check((await editor.inputValue()).length === 500001, "超限保留编辑全文");
  await editor.fill(original);
  await toggle.check();
  check(await page.locator(".diff-summary").textContent() === "内容一致，暂无修改" && await page.locator(".diff-row.modified,.diff-row.added,.diff-row.removed").count() === 0, "恢复原文清空旧差异");
  await page.reload();
  await page.locator("#markdown-lens-root").waitFor();
  check(!await toggle.isChecked(), "刷新清空对比状态");
  await page.getByRole("button", {name:"编辑",exact:true}).click();
  check(await editor.inputValue() === original, "刷新恢复原始内容");
  await page.setViewportSize({width:1440,height:1000});
  return {passed:results.length,results,expectedDownload:draft};
}
